def patch_params(text: str, target: str) -> str:
    text = replace_once(text,
        '    pub fast_sync_read: bool,\n}',
        '    pub fast_sync_read: bool,\n'
        '    /// Empty keeps the official hardware calibration and fixed IMU mount.\n'
        '    pub calibration_path: String,\n}', PARAMS)
    text = replace_once(text,
        '            fast_sync_read: true,\n',
        '            fast_sync_read: true,\n            calibration_path: String::new(),\n', PARAMS)
    text = replace_once(text,
        'impl Default for Control {',
        RUST_CALIBRATION.replace('__TARGET__', target) + '\nimpl Default for Control {', PARAMS)
    text = replace_once(text,
        '    Rate { path: String, got: u32 },',
        '    Rate { path: String, got: u32 },\n'
        '    #[error("{path}: invalid robot calibration: {reason}")]\n'
        '    Calibration { path: String, reason: String },', PARAMS)
    text = replace_once(text,
        '    fn validate(&self, path: &Path) -> Result<(), ParamsError> {',
        '    fn validate(&self, path: &Path) -> Result<(), ParamsError> {\n'
        '        self.bus.load_calibration().map_err(|reason| ParamsError::Calibration {\n'
        '            path: path.display().to_string(), reason,\n'
        '        })?;', PARAMS)
    return text + '\n' + PARAMS_TESTS.replace('__TARGET__', target)


