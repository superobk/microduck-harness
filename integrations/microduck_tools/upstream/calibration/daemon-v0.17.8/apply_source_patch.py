def patch_imu(text: str) -> str:
    """Keep factory sensitivity as identity when calibration is absent; change raw->rad/s only."""
    text = replace_once(text,
        '    mount: [f64; 4],\n',
        '    mount: [f64; 4],\n'
        '    /// Runtime configured gyro units: radians/second per raw i16 count.\n'
        '    gyro_rad_per_lsb: f64,\n', IMU)
    text = replace_once(text,
        '            mount,\n            last_quat: [1.0, 0.0, 0.0, 0.0],',
        '            mount,\n            gyro_rad_per_lsb: GYRO_RAD_PER_LSB,\n'
        '            last_quat: [1.0, 0.0, 0.0, 0.0],', IMU)
    text = replace_once(text,
        '    pub fn decode(&mut self, raw: &[u8; IMU_BLOCK_LEN]) -> ImuData {',
        '    /// This only changes host decode sensitivity, not the sensor register FS.\n'
        '    pub fn set_gyro_raw_counts_per_dps(&mut self, counts: f64) {\n'
        '        self.gyro_rad_per_lsb = std::f64::consts::PI / (180.0 * counts);\n'
        '    }\n'
        '    pub fn gyro_raw_counts_per_dps(&self) -> f64 {\n'
        '        std::f64::consts::PI / (180.0 * self.gyro_rad_per_lsb)\n'
        '    }\n'
        '    pub fn mount(&self) -> [f64; 4] { self.mount }\n\n'
        '    pub fn decode(&mut self, raw: &[u8; IMU_BLOCK_LEN]) -> ImuData {', IMU)
    text = replace_once(text,
        'as f64 * GYRO_RAD_PER_LSB',
        'as f64 * self.gyro_rad_per_lsb', IMU) if text.count('as f64 * GYRO_RAD_PER_LSB') == 1 else text.replace('as f64 * GYRO_RAD_PER_LSB','as f64 * self.gyro_rad_per_lsb')
    if text.count('as f64 * self.gyro_rad_per_lsb') != 3:
        raise ValueError('imu: expected three axes to use instance gyro scale')
    text += r"""
#[cfg(test)]
mod microduck_calibration_gyro_tests {
    use super::*;
    #[test]
    fn conversion_is_radians_per_second_and_factory_default_is_unchanged() {
        let mut d = SflpDecoder::default();
        assert!((d.gyro_raw_counts_per_dps() - (1.0 / 0.0175)).abs() < 1e-9);
        d.set_gyro_raw_counts_per_dps(16.4);
        let mut raw = [0u8; IMU_BLOCK_LEN];
        raw[0..2].copy_from_slice(&(164i16).to_le_bytes());
        d.decode(&raw);
        d.decode(&raw);
        let out = d.decode(&raw);
        let length = out.gyro.iter().map(|x| x*x).sum::<f64>().sqrt();
        assert!((length - 10f64.to_radians()).abs() < 1e-9);
    }
}
"""
    return text

def patch_main(text: str, tag: str = 'daemon-v0.17.8') -> str:
    text = replace_once(text,
        '    io.set_imu_mount(body_imu_mount(board));',
        '    // A single validated file supplies both joint mapping and raw gyro sensitivity.\n'
        '    let calibration = match bus.load_calibration() {\n'
        '        Ok(value) => value,\n'
        '        Err(error) => {\n'
        '            tracing::error!(%error, "cannot load robot calibration");\n'
        '            return None;\n'
        '        }\n'
        '    };\n'
        '    let imu_mount = calibration.as_ref().map(|c| c.imu_mount_wxyz)\n'
        '        .unwrap_or_else(|| body_imu_mount(board));\n'
        '    io.set_imu_mount(imu_mount);\n'
        '    if let Some(cal) = calibration.as_ref() {\n'
        '        if let Err(error) = io.set_joint_calibration(cal.joint_zero_rad, cal.joint_direction) {\n'
        '            tracing::error!(%error, "cannot configure joint calibration");\n'
        '            return None;\n'
        '        }\n'
        '        io.set_gyro_raw_counts_per_dps(cal.gyro_raw_counts_per_dps);\n'
        '        tracing::info!(path = %bus.calibration_path, gyro_profile = %cal.gyro_profile,\n'
        '            counts_per_dps = cal.gyro_raw_counts_per_dps,\n'
        '            "software-only servo and IMU calibration active");\n'
        '    }', MAIN)
    # Snapshot is written ONLY after the daemon has opened and pinged the whole bus.
    anchor = '                    state.startup_imu_missing.store(false, Ordering::Relaxed);\n                    return Some(io);'
    text = replace_once(text,anchor,
        '                    state.startup_imu_missing.store(false, Ordering::Relaxed);\n'
        '                    #[cfg(target_os = "linux")]\n'
        '                    if let Err(error) = write_effective_calibration(&io, bus) {\n'
        '                        tracing::warn!(%error, "cannot publish runtime-effective calibration");\n'
        '                    }\n'
        '                    return Some(io);', MAIN)
    marker='/// Open and verify the bus, or explain why not.\n/// The body IMU'
    snapshot = r"""/// Report only what the live DynamixelIo decoder really holds, never re-read a
/// changed calibration file and mistake pending settings for active settings.
#[cfg(target_os = "linux")]
fn write_effective_calibration(io: &duck_control::bus::DynamixelIo, bus: &params::Bus)
    -> std::io::Result<()> {
    let (zeros, dirs, mount, counts) = io.effective_calibration();
    let payload = serde_json::json!({
        "source": "robotd:DynamixelIo:live",
        "target_tag": "__TARGET__",
        "pid": std::process::id(),
        "bus_verified": true,
        "calibration_path": bus.calibration_path,
        "imu_module": "bus_imu200",
        "gyro_raw_counts_per_dps": counts,
        "gyro_rad_per_raw_count": std::f64::consts::PI / (180.0 * counts),
        "gyro_deg_per_raw_count": 1.0 / counts,
        "imu_mount_wxyz": mount,
        "joint_zero_rad": zeros,
        "joint_direction": dirs,
    });
    let dir = std::path::Path::new("/run/robotd");
    let tmp = dir.join(format!(".calibration-effective-{}.tmp", std::process::id()));
    let dest = dir.join("calibration-effective.json");
    let bytes = serde_json::to_vec_pretty(&payload).map_err(std::io::Error::other)?;
    std::fs::write(&tmp, bytes)?;
    std::fs::rename(&tmp, &dest)
}

"""
    snapshot = snapshot.replace('__TARGET__', tag)
    return replace_once(text,marker,snapshot+marker,MAIN)


def run(repo: Path, tag: str, dry_run: bool) -> None:
    if tag not in SUPPORTED:
        raise ValueError(f'unsupported target {tag}')
    if not (repo / '.git').exists():
        raise ValueError('repository .git missing; pass a cloned official repository')
    head_tag = subprocess.run(['git', 'rev-parse', '--verify', f'{tag}^{{commit}}'], cwd=repo,
                             check=True, capture_output=True, text=True).stdout.strip()
    head = subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=repo, check=True,
                          capture_output=True, text=True).stdout.strip()
    if head_tag != EXPECTED_TAG_COMMITS[tag]:
        raise ValueError(f'{tag} does not point to verified upstream SHA {EXPECTED_TAG_COMMITS[tag]}')
    if head != head_tag:
        raise ValueError(f'HEAD {head[:12]} is not official {tag} at {head_tag[:12]}')
    paths = [PARAMS, REGISTRY, BUS, IMU, MAIN]
    dirty = subprocess.run(['git', 'status', '--porcelain', '--', *paths], cwd=repo,
                           check=True, capture_output=True, text=True).stdout.strip()
    if dirty:
        raise ValueError('source files are already modified; commit/stash first:\n' + dirty)
    funcs = {PARAMS: lambda s: patch_params(s, tag), REGISTRY: patch_registry,
             BUS: patch_bus, IMU: patch_imu, MAIN: lambda s: patch_main(s, tag)}
    edits = {}
    for p in paths:
        f = repo / p
        old = f.read_text(encoding='utf-8')
        new = funcs[p](old)
        if new == old:
            raise ValueError(f'{p} was unchanged unexpectedly')
        edits[f] = new
    for p, s in edits.items():
        print(f'{"would patch" if dry_run else "patching"}: {p.relative_to(repo)}')
        if not dry_run:
            p.write_text(s, encoding='utf-8')
    if not dry_run:
        print('Done. Run cargo fmt, cargo test, and examine git diff before any deployment.')


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--repo', required=True, type=Path)
    ap.add_argument('--target', required=True, choices=sorted(SUPPORTED))
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()
    try:
        run(a.repo.resolve(), a.target, a.dry_run)
    except (OSError, ValueError, subprocess.CalledProcessError) as e:
        ap.error(str(e))
