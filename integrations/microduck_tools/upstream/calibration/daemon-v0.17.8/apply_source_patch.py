#!/usr/bin/env python3
"""Integrate configuration-driven non-EEPROM calibration into a pinned official Microduck tree.

This is intentionally a strict, reversible *source* patcher. Refuses unknown tags,
changed anchor text or dirty files. Run tests and review `git diff` after invocation.
"""
